import { expect, test } from "@playwright/test";
import { defaultGeneralSettings, type AssistantMessage } from "@skladno/shared";


test("protected translation values support pointer, keyboard, and narrow comparison without changing Article text", async ({ page }) => {
    const service = "http://127.0.0.1:8787";
    const url = "https://example.com/" + "long-path/".repeat(30);
    const code = "const result = call();\n\nreturn result;";
    const content = `Protected translation fixture.\nAPI-v2 42 42 ${url} "Quoted value"\n${code}`;
    const configured = await page.request.put(`${service}/api/settings/general`, { data: { ...defaultGeneralSettings, defaultTranslationLanguages: ["es"] } });
    expect(configured.ok()).toBe(true);
    const created = await page.request.post(`${service}/api/articles`, { data: { title: "Protected source", content, language: "en" } });
    expect(created.ok()).toBe(true);
    const article = await created.json();
    await page.addInitScript((id) => {
        localStorage.setItem("skladno.quick-start.v1", "complete");
        localStorage.setItem("skladno-workspace-layout", JSON.stringify({ version: 3, view: "translations", selectedArticleId: id }));
    }, article.id);
    await page.goto("/");
    await page.getByRole("tab", { name: /Translations/ }).click();
    await page.getByRole("button", { name: "New translation…", exact: true }).click();
    await page.getByRole("dialog").getByRole("button", { name: "Generate Spanish translation", exact: true }).click();
    const comparison = page.getByLabel(/^Translation comparison/);
    const first = comparison.getByRole("button", { name: "Validated protected content: API-v2", exact: true }).first();
    await expect(first).toBeVisible();
    await expect(comparison.getByRole("status")).toHaveCount(0);
    await expect(comparison.getByRole("button", { name: "Validated protected content: 42", exact: true, includeHidden: true })).toHaveCount(4);
    await expect(first).toHaveAccessibleDescription(/Marked for exact preservation.*expected occurrence is present unchanged/);
    await first.hover();
    await expect(first).toHaveAttribute("title", /This check is advisory/);
    await first.click();
    await expect(first).toHaveAttribute("aria-expanded", "true");
    await page.keyboard.press("Escape");
    await expect(first).toHaveAttribute("aria-expanded", "false");
    await page.getByRole("tab", { name: /Translations/ }).focus();
    await page.keyboard.press("Tab");
    await expect(comparison).toBeFocused();
    await page.keyboard.press("ArrowRight");
    await expect(first).toBeFocused();
    await page.keyboard.press("Enter");
    await expect(first).toHaveAttribute("aria-expanded", "true");
    await page.keyboard.press("Space");
    await expect(first).toHaveAttribute("aria-expanded", "false");
    await page.keyboard.press("ArrowRight");
    await expect(comparison.getByRole("button", { name: "Validated protected content: 42", exact: true }).first()).toBeFocused();
    await page.keyboard.press("ArrowLeft");
    await expect(first).toBeFocused();
    await page.getByRole("button", { name: "Aligned paragraphs" }).click();
    await expect(comparison.getByRole("button", { name: `Validated protected content: ${code}`, exact: true })).toHaveCount(2);
    await page.getByRole("button", { name: "Collapse Editorial Assistant Panel", exact: true }).click();
    await page.setViewportSize({ width: 640, height: 800 });
    await page.getByRole("button", { name: "Side by side" }).click();
    const resultTab = comparison.getByRole("tab", { name: "Spanish translation", exact: true });
    await resultTab.click();
    const longValue = comparison.getByRole("button", { name: `Validated protected content: ${url}`, exact: true });
    await expect(longValue).toBeVisible();
    await longValue.click();
    await expect(longValue).toHaveAttribute("aria-expanded", "true");
    expect(await comparison.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
    await comparison.focus();
    await page.keyboard.press("ArrowLeft");
    await expect(comparison.getByRole("button", { name: `Validated protected content: ${code}`, exact: true })).toBeFocused();
    const stored = await (await page.request.get(`${service}/api/articles/${article.id}`)).json();
    expect(stored.currentRevision.content).toBe(content);
    expect(stored.currentRevisionId).toBe(article.currentRevisionId);
    const messages: AssistantMessage[] = await (await page.request.get(`${service}/api/articles/${article.id}/assistant/messages`)).json();
    expect(messages.find((message) => message.translation)?.translation?.content).toBe(content.replace("Protected translation fixture.", "Traducción protegida."));
});
